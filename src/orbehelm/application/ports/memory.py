"""Canonical KUnit persistence and interchangeable retrieval/embedding ports."""
from typing import Protocol


class EmbeddingPort(Protocol):
    model_id: str
    def documents(self, texts: list[str]) -> list[list[float]]: ...
    def query(self, text: str) -> list[float]: ...


class MemoryStore(Protocol):
    def put(self, owner, content, source_id, visibility, binding_id=None, source_ids=(), source_kind='explicit'): ...
    def read_unit(self, owner, unit_id, binding_id=None): ...
    def search(self, owner, query, limit, binding_id=None): ...
    def revise(self, owner, unit_id, expected, content=None, visibility=None, retract=False): ...
    def history(self, owner, unit_id): ...
    def policy_epoch(self) -> int: ...
